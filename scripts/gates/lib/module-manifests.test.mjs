import assert from "node:assert/strict"
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { test } from "node:test"

import {
  GENERATED_HOST,
  GENERATED_UI,
  findManifestFiles,
  manifestKind,
  renderRegistries,
  validateHostManifest,
  validateUiManifest,
} from "./module-manifests.mjs"

const lazy = (spec) => ({ $lazy: spec })

test("manifestKind recognises the two manifest paths and nothing else", () => {
  assert.deepEqual(manifestKind("lib/pet/module.ts"), {
    layer: "host",
    id: "pet",
    helper: "defineHostModule",
  })
  assert.deepEqual(manifestKind("components/pet/module.ui.ts"), {
    layer: "ui",
    id: "pet",
    helper: "defineUiModule",
  })
  assert.equal(manifestKind("lib/pet/sub/module.ts"), null)
  assert.equal(manifestKind("components/pet/module.ts"), null)
})

test("findManifestFiles lists manifests one directory deep, sorted", () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "module-manifests-")))
  try {
    for (const file of [
      "lib/b/module.ts",
      "lib/a/module.ts",
      "lib/a/deep/module.ts",
      "components/a/module.ui.ts",
      "components/a/module.ts",
    ]) {
      mkdirSync(join(root, dirname(file)), { recursive: true })
      writeFileSync(join(root, file), "")
    }
    assert.deepEqual(findManifestFiles(root), [
      "components/a/module.ui.ts",
      "lib/a/module.ts",
      "lib/b/module.ts",
    ])
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

test("a slash command is a named, described, lazily loaded descriptor", () => {
  const base = { id: "crew", kind: "module", stage: "beta" }
  assert.deepEqual(
    validateHostManifest(
      {
        ...base,
        searchProviders: lazy("./search"),
        slashCommands: [
          {
            name: "crew",
            description: "Talk.",
            category: "goal",
            argumentHint: "<x>",
            argumentOptions: ["x"],
            load: lazy("./slash"),
          },
        ],
        messages: "crew",
      },
      "crew"
    ),
    []
  )
  const errors = validateHostManifest(
    {
      ...base,
      searchProviders: "./search",
      slashCommands: [
        { name: "/Crew", load: () => 0, extra: 1 },
        { name: "dup", description: "a", load: lazy("./a") },
        { name: "dup", description: "b", load: lazy("./b") },
      ],
    },
    "crew"
  )
  for (const expected of [
    "searchProviders is a lazy entry",
    'slashCommands[0]: unknown field "extra"',
    "slashCommands[0].name is lower-case kebab",
    "slashCommands[0].description is required",
    "slashCommands[0].load is a lazy entry",
    'slashCommands[2].name "dup" is listed twice',
  ])
    assert.ok(
      errors.some((e) => e.startsWith(expected)),
      `${expected} in ${errors}`
    )
})

test("a settings section names its group, a catalog icon, full keys and a lazy load", () => {
  const section = {
    id: "crew",
    group: "agents",
    icon: "Users",
    label: "crew.settingsSection.label",
    description: "crew.settingsSection.description",
    after: "subagents",
    requires: ["keyring"],
    profiles: ["desktop"],
    layout: "fill",
    keywords: ["crew"],
    load: lazy("./section"),
  }
  const icons = new Set(["Users"])
  assert.deepEqual(
    validateUiManifest({ id: "crew", settingsSections: [section] }, "crew", icons),
    []
  )
  const errors = validateUiManifest(
    {
      id: "crew",
      settingsSections: [
        { ...section, icon: "Nope", label: "plain", layout: "wide", keywords: "crew" },
        { ...section, group: "" },
        section,
      ],
    },
    "crew",
    icons
  )
  for (const expected of [
    'settingsSections[0].icon "Nope" is not a Lucide icon name',
    "settingsSections[0].label is a full i18n key",
    'settingsSections[0].layout is "fill" or absent',
    "settingsSections[0].keywords is a list of strings",
    "settingsSections[1].group is required",
    'settingsSections[1].id "crew" is listed twice',
  ])
    assert.ok(
      errors.some((e) => e.startsWith(expected)),
      `${expected} in ${errors}`
    )
})

test("renderRegistries imports every manifest in id order and lists it", () => {
  const files = renderRegistries({
    host: [
      { id: "web-reader", file: "lib/web-reader/module.ts" },
      { id: "crew", file: "lib/crew/module.ts" },
    ],
    ui: [],
  })
  const host = files[GENERATED_HOST]
  assert.ok(host.startsWith("// Generated by scripts/build/gen-module-registry.mjs"))
  assert.ok(
    host.includes(
      'import crewModule from "@/lib/crew/module"\nimport webReaderModule from "@/lib/web-reader/module"\n'
    )
  )
  assert.ok(host.endsWith("export const HOST_MODULES = [crewModule, webReaderModule] as const\n"))
  assert.ok(files[GENERATED_UI].endsWith("\n\nexport const UI_MODULES = [] as const\n"))
})
